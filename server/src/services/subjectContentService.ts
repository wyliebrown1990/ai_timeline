/**
 * Generate a learning path from a subject's content
 * Creates a chronological journey through the subject's milestones
 */
export async function generateSubjectLearningPath(
  subjectSlug: string
): Promise<GeneratedLearningPath | null> {
  if (!prisma) throw new Error('Database not available');

  const subject = await prisma.subject.findUnique({
    where: { slug: subjectSlug },
  });

  if (!subject) return null;

  // Get milestones for this subject (primary only to avoid tangents)
  const milestoneLinks = await prisma.contentSubject.findMany({
    where: {
      subjectId: subject.id,
      contentType: 'milestone',
      isPrimary: true,
    },
    select: { contentId: true },
  });

  const milestones = await prisma.milestone.findMany({
    where: { id: { in: milestoneLinks.map(l => l.contentId) } },
    orderBy: { date: 'asc' },
    take: 20, // Limit to reasonable path length
  });

  // Get related glossary terms
  const glossaryLinks = await prisma.contentSubject.findMany({
    where: {
      subjectId: subject.id,
      contentType: 'glossary_term',
    },
    select: { contentId: true },
  });

  const glossaryTerms = await prisma.glossaryTerm.findMany({
    where: { id: { in: glossaryLinks.map(l => l.contentId) } },
    select: { term: true },
  });

  // Generate key takeaways from milestone titles
  const keyTakeaways = generateKeyTakeaways(milestones, subject.name);

  return {
    title: `History of ${subject.name}`,
    slug: `subject-${subject.slug}`,
    description: `Explore the key milestones in ${subject.name}, from early developments to recent breakthroughs.`,
    targetAudience: `Anyone interested in ${subject.name}`,
    difficulty: (subject.defaultDifficulty as string) || 'intermediate',
    estimatedMinutes: milestones.length * 5, // 5 minutes per milestone
    milestoneIds: milestones.map(m => m.id),
    conceptsCovered: glossaryTerms.map(t => t.term),
    keyTakeaways,
    isAutoGenerated: true,
    subjectSlug: subject.slug,
  };
}

/**
 * Generate a learning path spanning multiple subjects
 */
export async function generateCrossSubjectPath(
  subjectSlugs: string[],
  options: { title?: string; maxMilestones?: number } = {}
): Promise<GeneratedLearningPath | null> {
  if (!prisma) throw new Error('Database not available');

  const subjects = await prisma.subject.findMany({
    where: { slug: { in: subjectSlugs } },
  });

  if (subjects.length === 0) return null;

  // Get all milestones for these subjects
  const milestoneLinks = await prisma.contentSubject.findMany({
    where: {
      subjectId: { in: subjects.map(s => s.id) },
      contentType: 'milestone',
    },
    select: { contentId: true },
    distinct: ['contentId'],
  });

  const milestones = await prisma.milestone.findMany({
    where: { id: { in: milestoneLinks.map(l => l.contentId) } },
    orderBy: { date: 'asc' },
    take: options.maxMilestones || 20,
  });

  const subjectNames = subjects.map(s => s.name).join(' & ');

  // Generate key takeaways
  const keyTakeaways = generateKeyTakeaways(milestones, subjectNames);

  return {
    title: options.title || `${subjectNames}: A Combined History`,
    slug: `cross-${subjectSlugs.join('-')}`,
    description: `Explore how ${subjectNames} have evolved together through key milestones.`,
    targetAudience: `Anyone interested in ${subjectNames}`,
    difficulty: 'intermediate',
    estimatedMinutes: milestones.length * 5,
    milestoneIds: milestones.map(m => m.id),
    conceptsCovered: [],
    keyTakeaways,
    isAutoGenerated: true,
    crossSubjectSlugs: subjectSlugs,
  };
}

/**
 * Generate key takeaways from milestones
 */
function generateKeyTakeaways(
  milestones: { title: string; significance: number; date: Date }[],
  subjectName: string
): string[] {
  const takeaways: string[] = [];

  if (milestones.length === 0) {
    return [`Explore the history of ${subjectName}`];
  }

  // Get date range
  const firstYear = milestones[0]?.date.getFullYear();
  const lastYear = milestones[milestones.length - 1]?.date.getFullYear();
  if (firstYear && lastYear) {
    takeaways.push(`Understand ${subjectName} from ${firstYear} to ${lastYear}`);
  }

  // Get most significant milestones
  const significant = milestones
    .filter(m => m.significance >= 3)
    .slice(0, 3);

  for (const m of significant) {
    takeaways.push(`Learn about ${m.title}`);
  }

  // If we still need more, add generic ones
  if (takeaways.length < 3) {
    takeaways.push(`Trace the evolution of key concepts in ${subjectName}`);
  }

  return takeaways.slice(0, 5);
}

