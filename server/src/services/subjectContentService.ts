export interface RelatedContentItem {
  contentType: ContentType;
  contentId: string;
  title: string;
  overlapScore: number; // Number of shared subjects
}

/**
 * Get content that shares subjects with a given piece of content
 */
export async function getRelatedContent(
  contentType: ContentType,
  contentId: string,
  limit = 5
): Promise<RelatedContentItem[]> {
  if (!prisma) throw new Error('Database not available');

  // Get subjects for this content
  const contentSubjects = await prisma.contentSubject.findMany({
    where: { contentType, contentId },
    select: { subjectId: true },
  });

  if (contentSubjects.length === 0) return [];

  const subjectIds = contentSubjects.map(cs => cs.subjectId);

  // Find other content with same subjects
  const related = await prisma.contentSubject.findMany({
    where: {
      subjectId: { in: subjectIds },
      NOT: {
        AND: [{ contentType }, { contentId }],
      },
    },
    select: { contentType: true, contentId: true, subjectId: true },
  });

  // Score by number of overlapping subjects
  const scoreMap = new Map<string, { type: ContentType; id: string; score: number }>();

  for (const r of related) {
    const key = `${r.contentType}:${r.contentId}`;
    const existing = scoreMap.get(key);
    if (existing) {
      existing.score++;
    } else {
      scoreMap.set(key, {
        type: r.contentType as ContentType,
        id: r.contentId,
        score: 1,
      });
    }
  }

  // Sort by score and get top N
  const sorted = Array.from(scoreMap.values())
    .sort((a, b) => b.score - a.score)
    .slice(0, limit);

  // Hydrate with titles
  const results: RelatedContentItem[] = [];

  for (const item of sorted) {
    let title = '';

    switch (item.type) {
      case 'milestone': {
        const m = await prisma.milestone.findUnique({
          where: { id: item.id },
          select: { title: true },
        });
        title = m?.title || 'Unknown Milestone';
        break;
      }
      case 'glossary_term': {
        const t = await prisma.glossaryTerm.findUnique({
          where: { id: item.id },
          select: { term: true },
        });
        title = t?.term || 'Unknown Term';
        break;
      }
      case 'current_event': {
        const e = await prisma.currentEvent.findUnique({
          where: { id: item.id },
          select: { headline: true },
        });
        title = e?.headline || 'Unknown Event';
        break;
      }
      case 'person': {
        const p = await prisma.person.findUnique({
          where: { id: item.id },
          select: { canonicalName: true },
        });
        title = p?.canonicalName || 'Unknown Person';
        break;
      }
      case 'organization': {
        const o = await prisma.organization.findUnique({
          where: { id: item.id },
          select: { name: true },
        });
        title = o?.name || 'Unknown Organization';
        break;
      }
    }

    results.push({
      contentType: item.type,
      contentId: item.id,
      title,
      overlapScore: item.score,
    });
  }

  return results;
}
