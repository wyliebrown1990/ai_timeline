/**
 * Get hydrated content for a subject
 * Fetches actual content objects, not just IDs
 */
export async function getContentBySubject(
  subjectSlug: string,
  options: SubjectContentQuery = {}
): Promise<SubjectContent> {
  if (!prisma) throw new Error('Database not available');

  // Get the subject
  const subject = await prisma.subject.findUnique({
    where: { slug: subjectSlug },
  });

  if (!subject) {
    return {
      milestones: [],
      glossaryTerms: [],
      currentEvents: [],
      persons: [],
      organizations: [],
      total: 0,
    };
  }

  // Get subject IDs to query (including children if requested)
  let subjectIds = [subject.id];
  if (options.includeChildren) {
    const descendants = await getDescendants(subject.id);
    subjectIds = [...subjectIds, ...descendants.map(d => d.id)];
  }

  // Determine which content types to query
  const contentTypes = options.contentTypes || [
    'milestone',
    'glossary_term',
    'current_event',
    'person',
    'organization',
  ];

  // Build base query for ContentSubject
  const baseWhere = {
    subjectId: { in: subjectIds },
    ...(options.primaryOnly ? { isPrimary: true } : {}),
  };

  const result: SubjectContent = {
    milestones: [],
    glossaryTerms: [],
    currentEvents: [],
    persons: [],
    organizations: [],
    total: 0,
  };

  // Fetch each content type
  if (contentTypes.includes('milestone')) {
    const milestoneLinks = await prisma.contentSubject.findMany({
      where: { ...baseWhere, contentType: 'milestone' },
      select: { contentId: true, confidence: true },
      distinct: ['contentId'],
    });

    if (milestoneLinks.length > 0) {
      const milestones = await prisma.milestone.findMany({
        where: { id: { in: milestoneLinks.map(l => l.contentId) } },
        select: {
          id: true,
          title: true,
          description: true,
          date: true,
          category: true,
          significance: true,
          organizationId: true,
          sourceUrl: true,
          tags: true,
          tldr: true,
        },
        orderBy: options.sortBy === 'significance'
          ? { significance: 'desc' }
          : options.sortBy === 'date'
            ? { date: 'desc' }
            : { date: 'desc' },
        take: options.limit,
        skip: options.offset,
      });

      result.milestones = milestones;
    }
  }

  if (contentTypes.includes('glossary_term')) {
    const glossaryLinks = await prisma.contentSubject.findMany({
      where: { ...baseWhere, contentType: 'glossary_term' },
      select: { contentId: true },
      distinct: ['contentId'],
    });

    if (glossaryLinks.length > 0) {
      const terms = await prisma.glossaryTerm.findMany({
        where: { id: { in: glossaryLinks.map(l => l.contentId) } },
        select: {
          id: true,
          term: true,
          shortDefinition: true,
          fullDefinition: true,
          category: true,
        },
        orderBy: { term: 'asc' },
        take: options.limit,
        skip: options.offset,
      });

      result.glossaryTerms = terms;
    }
  }

  if (contentTypes.includes('current_event')) {
    const eventLinks = await prisma.contentSubject.findMany({
      where: { ...baseWhere, contentType: 'current_event' },
      select: { contentId: true },
      distinct: ['contentId'],
    });

    if (eventLinks.length > 0) {
      const events = await prisma.currentEvent.findMany({
        where: { id: { in: eventLinks.map(l => l.contentId) } },
        select: {
          id: true,
          headline: true,
          summary: true,
          publishedDate: true,
          sourceUrl: true,
        },
        orderBy: { publishedDate: 'desc' },
        take: options.limit,
        skip: options.offset,
      });

      result.currentEvents = events;
    }
  }

  if (contentTypes.includes('person')) {
    const personLinks = await prisma.contentSubject.findMany({
      where: { ...baseWhere, contentType: 'person' },
      select: { contentId: true },
      distinct: ['contentId'],
    });

    if (personLinks.length > 0) {
      const persons = await prisma.person.findMany({
        where: { id: { in: personLinks.map(l => l.contentId) } },
        select: {
          id: true,
          canonicalName: true,
          slug: true,
          shortBio: true,
          role: true,
          focusAreas: true,
          imageUrl: true,
        },
        orderBy: { canonicalName: 'asc' },
        take: options.limit,
        skip: options.offset,
      });

      result.persons = persons;
    }
  }

  if (contentTypes.includes('organization')) {
    const orgLinks = await prisma.contentSubject.findMany({
      where: { ...baseWhere, contentType: 'organization' },
      select: { contentId: true },
      distinct: ['contentId'],
    });

    if (orgLinks.length > 0) {
      const orgs = await prisma.organization.findMany({
        where: { id: { in: orgLinks.map(l => l.contentId) } },
        select: {
          id: true,
          name: true,
          slug: true,
          shortDescription: true,
          type: true,
          focusAreas: true,
          logoUrl: true,
        },
        orderBy: { name: 'asc' },
        take: options.limit,
        skip: options.offset,
      });

      result.organizations = orgs;
    }
  }

  result.total =
    result.milestones.length +
    result.glossaryTerms.length +
    result.currentEvents.length +
    result.persons.length +
    result.organizations.length;

  return result;
}

