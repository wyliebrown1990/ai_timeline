export interface HydratedMilestone {
  id: string;
  title: string;
  description: string;
  date: Date;
  category: string;
  significance: number;
  organizationId: string | null;
  sourceUrl: string | null;
  tags: string;
  tldr: string | null;
}

export interface HydratedGlossaryTerm {
  id: string;
  term: string;
  shortDefinition: string;
  fullDefinition: string;
  category: string | null;
}

export interface HydratedCurrentEvent {
  id: string;
  headline: string;
  summary: string;
  publishedAt: Date;
  sourceUrl: string | null;
}

export interface HydratedPerson {
  id: string;
  canonicalName: string;
  slug: string;
  shortBio: string;
  role: string | null;
  focusAreas: string;
  imageUrl: string | null;
}

export interface HydratedOrganization {
  id: string;
  name: string;
  slug: string;
  shortDescription: string;
  type: string;
  focusAreas: string;
  logoUrl: string | null;
}

export interface SubjectContent {
  milestones: HydratedMilestone[];
  glossaryTerms: HydratedGlossaryTerm[];
  currentEvents: HydratedCurrentEvent[];
  persons: HydratedPerson[];
  organizations: HydratedOrganization[];
  total: number;
}

export interface GeneratedLearningPath {
  title: string;
  slug: string;
  description: string;
  targetAudience: string;
  difficulty: string;
  estimatedMinutes: number;
  milestoneIds: string[];
  conceptsCovered: string[];
  keyTakeaways: string[];
  isAutoGenerated: boolean;
  subjectSlug?: string;
  crossSubjectSlugs?: string[];
}

